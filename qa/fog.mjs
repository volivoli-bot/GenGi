const p=await b.newPage(); await p.setViewport({width:390,height:844});
await p.goto((process.env.GENGI_BASE||'http://localhost:4173/')+'?debug=1&noelite'); await p.waitForFunction(()=>window.gengi);
await p.evaluate(()=>gengi.reset()).catch(()=>{}); await sleep(600); await p.waitForFunction(()=>window.gengi);
await p.evaluate(()=>gengi.start()); await sleep(1000);
await p.evaluate(()=>{gengi.clearEnemies();gengi.minute(15);}); 
const a=await p.evaluate(()=>gengi.raid().snap.player.hp); await sleep(3000);
const r=await p.evaluate(()=>({hp:gengi.raid()?.snap.player.hp,el:gengi.raid()?.snap.elapsed, idle:gengi.raid()?.enemies.list.filter(e=>e.type==='corredor').length}));
console.log('niebla', a, JSON.stringify(r));
await b.close();
